def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true", help="每句都印，不只印接不到的")
    ap.add_argument("--max", type=int, default=12, help="接不到超過這個數就回失敗")
    args = ap.parse_args()

    misses = []
    for q in QUESTIONS:
        hit = health_kb.match_topics(q)
        if not hit:
            misses.append(q)
            print(f"❌ 接不到　{q}")
        elif args.all:
            print(f"✅ {hit[0]}　{q}")

    total = len(QUESTIONS)
    print()
    print(f"共 {total} 句　接得到 {total - len(misses)}　接不到 {len(misses)}"
          f"（門檻 {args.max}）")
    if len(misses) > args.max:
        print("⛔ 接不到的句子超過門檻——這些話她會自由發揮，不是我們審過的內容")
        return 1
    print("✅ 覆蓋率過關")
    return 0


if __name__ == "__main__":
    sys.exit(main())
